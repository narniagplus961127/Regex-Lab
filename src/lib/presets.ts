import type { Example, Mode } from "./regex";
export const PRESET_CATEGORIES = [
  "Everyday",
  "Validation",
  "Dates & numbers",
  "Developer",
  "Text",
] as const;
export type Preset = {
  id: string;
  name: string;
  category: (typeof PRESET_CATEGORIES)[number];
  description: string;
  pattern: string;
  flags: string;
  mode: Mode;
  text: string;
  explanation: string;
  limitations: string[];
  examples: Example[];
  source?: string;
};
function recipe(
  id: string,
  name: string,
  category: Preset["category"],
  description: string,
  regex: RegExp,
  mode: Mode,
  text: string,
  negative: string,
  explanation: string,
  limitations: string[],
  source?: string,
): Preset {
  return {
    id,
    name,
    category,
    description,
    pattern: regex.source,
    flags: regex.flags,
    mode,
    text,
    explanation,
    limitations,
    source,
    examples: [
      { id: `${id}-positive`, text, shouldMatch: true },
      { id: `${id}-negative`, text: negative, shouldMatch: false },
    ],
  };
}
